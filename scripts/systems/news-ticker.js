const AI_NEWS_TICKER_POOL = [
  ...AI_NEWS_TICKER_MESSAGES,
  ...AI_NEWS_TICKER_MESSAGE_EXPANSION
];

const NEWS_TICKER_MODE_KEY = 'numberTycoonNewsMode';
const CURRENCY_STATUS_SCALE_KEY = 'numberTycoonCurrencyStatusScale';
const NEWS_TICKER_MODES = new Set(['all', 'human', 'ai']);
const NEWS_TICKER_SPEED_PX_PER_SECOND = 450;
const NEWS_TICKER_SIDE_PADDING = 24;
let newsTickerMode = localStorage.getItem(NEWS_TICKER_MODE_KEY) || 'all';

if (!NEWS_TICKER_MODES.has(newsTickerMode)) {
  newsTickerMode = 'all';
}

function currencyStatusScaleFromStorage() {
  const savedScale = Number(localStorage.getItem(CURRENCY_STATUS_SCALE_KEY));
  return Number.isFinite(savedScale) ? Math.min(4, Math.max(1, savedScale)) : 1;
}

function applyCurrencyStatusScale(rawScale) {
  const scale = Math.min(4, Math.max(1, Number(rawScale) || 1));
  if (currencyStatus) {
    currencyStatus.style.width = `${180 * scale}px`;
    currencyStatus.style.padding = `${8 * scale}px ${10 * scale}px`;
    currencyStatus.style.fontSize = `${12 * scale}px`;
    currencyStatus.style.setProperty('--currency-status-row-gap', `${12 * scale}px`);
  }
  document.documentElement.style.setProperty('--currency-status-mobile-space', `${Math.round(216 * scale)}px`);
  if (currencyStatusScaleInput) currencyStatusScaleInput.value = String(scale);
  if (currencyStatusScaleValue) currencyStatusScaleValue.textContent = `${scale.toFixed(1)}배`;
  return scale;
}

applyCurrencyStatusScale(currencyStatusScaleFromStorage());

function newsTickerMessagePool() {
  if (newsTickerMode === 'human') return HUMAN_NEWS_TICKER_MESSAGES;
  if (newsTickerMode === 'ai') return AI_NEWS_TICKER_POOL;
  return [...HUMAN_NEWS_TICKER_MESSAGES, ...AI_NEWS_TICKER_POOL];
}

function randomNewsTickerMessage(previousMessage = '') {
  const messages = newsTickerMessagePool();
  if (messages.length === 1) return messages[0];

  let nextMessage = previousMessage;
  while (nextMessage === previousMessage) {
    const index = Math.floor(Math.random() * messages.length);
    nextMessage = messages[index];
  }
  return nextMessage;
}

function startNewsTickerMessage(message) {
  if (!newsTickerText) return;

  newsTickerText.style.visibility = 'hidden';
  newsTickerText.classList.remove('is-running');
  newsTickerText.textContent = message;

  const trackWidth = newsTickerText.parentElement.getBoundingClientRect().width || window.innerWidth;
  const textWidth = newsTickerText.getBoundingClientRect().width;
  const start = trackWidth + NEWS_TICKER_SIDE_PADDING;
  const end = -textWidth - NEWS_TICKER_SIDE_PADDING;
  const distance = start - end;
  const duration = Math.max(1.8, distance / NEWS_TICKER_SPEED_PX_PER_SECOND);

  newsTickerText.style.setProperty('--ticker-start', `${start}px`);
  newsTickerText.style.setProperty('--ticker-end', `${end}px`);
  newsTickerText.style.setProperty('--ticker-duration', `${duration}s`);

  void newsTickerText.offsetWidth;
  newsTickerText.style.visibility = 'visible';
  newsTickerText.classList.add('is-running');
}

function setRandomNewsTickerMessage() {
  if (!newsTickerText) return;

  const message = randomNewsTickerMessage(newsTickerText.textContent);
  startNewsTickerMessage(message);
}

if (newsTickerText) {
  if (newsModeSelect) {
    newsModeSelect.value = newsTickerMode;
  }
  setRandomNewsTickerMessage();
  newsTickerText.addEventListener('animationend', setRandomNewsTickerMessage);
}

