const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const {root,loadCatalog,decode,hangul} = require('./localization-catalog.cjs');
const directory = path.join(root,'scripts/i18n');
const base = ['en-progression.js','en-interface.js','en-narrative.js','en-automation.js','en-formulas.js'];
const files = [...base,...fs.readdirSync(directory).filter(file=>/^en-supplement.*\.js$/.test(file)).sort()];
const entries = new Map();
const context = vm.createContext({window:{NumberTycoonI18n:{register(pairs) {
  for(const [source,target] of pairs) {
    const key=source.replace(/\s+/g,' ').trim();
    if(!entries.has(key))entries.set(key,target);
  }
}}}});
for(const file of files)vm.runInContext(fs.readFileSync(path.join(directory,file),'utf8'),context,{filename:file});
fs.writeFileSync(path.join(directory,'catalog-en.js'),
  '// Generated by tools/build-localization.cjs. Edit the en-* source catalogs.\n'
  +'window.NumberTycoonI18n.register('+JSON.stringify([...entries],null,2)+');\n');
const catalog=loadCatalog();
const escapeXml=text=>text.replace(/[&<>"']/g,char=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&apos;'})[char]);
const graphs=path.join(root,'assets/formula-graphs');
fs.mkdirSync(path.join(graphs,'en'),{recursive:true});
let count=0;
for(const file of fs.readdirSync(graphs).filter(file=>file.endsWith('.svg'))) {
  const source=fs.readFileSync(path.join(graphs,file),'utf8');
  const translated=source.replace(/(<text\b[^>]*>)([\s\S]*?)(<\/text>)/g,(_,open,text,close)=>
    open+escapeXml(catalog.text(decode(text)))+close)
    .replace(/aria-label="([^"]*)"/g,(_,label)=>'aria-label="'+escapeXml(catalog.text(decode(label)))+'"');
  const textOnly=[...translated.matchAll(/<text\b[^>]*>([\s\S]*?)<\/text>/g)].map(match=>match[1]);
  if(textOnly.some(text=>hangul.test(text)))throw Error('Untranslated graph: '+file);
  fs.writeFileSync(path.join(graphs,'en',file),translated);
  count++;
}
console.log(`${entries.size} catalog entries; ${count} English graphs generated.`);
